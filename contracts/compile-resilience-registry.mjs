#!/usr/bin/env node
/**
 * Reproducible build of contracts/KaizenResilienceRegistry.sol (T-9.4).
 * Same toolchain as compile-registry.mjs (plain solc → EVM bytecode for
 * pallet-revive with allowEVMBytecode, R-30). solc is not a dependency:
 *
 *   npm i --no-save solc@0.8.28
 *   node contracts/compile-resilience-registry.mjs
 *
 * Writes contracts/KaizenResilienceRegistry.artifact.json and
 * packages/engine/src/resilience/registry-artifact.ts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const PINNED = '0.8.28';
const NAME = 'KaizenResilienceRegistry';
let solc;
try {
  solc = (await import('solc')).default;
} catch {
  console.error(`solc not installed. Run: npm i --no-save solc@${PINNED}`);
  process.exit(1);
}
if (!solc.version().startsWith(PINNED)) {
  console.error(`expected solc ${PINNED}, got ${solc.version()}`);
  process.exit(1);
}
const source = fs.readFileSync(path.join(here, `${NAME}.sol`), 'utf8');
const settings = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: 'paris',
  outputSelection: {
    '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.methodIdentifiers'] },
  },
};
const out = JSON.parse(
  solc.compile(JSON.stringify({ language: 'Solidity', sources: { [`${NAME}.sol`]: { content: source } }, settings })),
);
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join('\n'));
  process.exit(1);
}
const c = out.contracts[`${NAME}.sol`][NAME];
const artifact = {
  contractName: NAME,
  compiler: `solc ${solc.version()}`,
  evmVersion: settings.evmVersion,
  optimizer: settings.optimizer,
  abi: c.abi,
  methodIdentifiers: c.evm.methodIdentifiers,
  bytecode: `0x${c.evm.bytecode.object}`,
  deployedBytecode: `0x${c.evm.deployedBytecode.object}`,
};
fs.writeFileSync(path.join(here, `${NAME}.artifact.json`), `${JSON.stringify(artifact, null, 2)}\n`);
const ts = `/**
 * GENERATED by contracts/compile-resilience-registry.mjs — do not edit by hand.
 * Source: contracts/${NAME}.sol (${artifact.compiler}, evm ${artifact.evmVersion}, optimizer runs ${settings.optimizer.runs}).
 */

export const KAIZEN_RESILIENCE_REGISTRY_ARTIFACT = ${JSON.stringify(artifact, null, 2)} as const;
`;
fs.writeFileSync(path.join(here, '..', 'packages', 'engine', 'src', 'resilience', 'registry-artifact.ts'), ts);
console.log(`compiled with ${artifact.compiler}: init ${c.evm.bytecode.object.length / 2} bytes, runtime ${c.evm.deployedBytecode.object.length / 2} bytes`);
