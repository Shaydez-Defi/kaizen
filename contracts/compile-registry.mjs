#!/usr/bin/env node
/**
 * Reproducible build of contracts/KaizenRunRegistry.sol (T-8.2).
 *
 * The Portaldot V3 runtime's pallet-revive reports `allowEVMBytecode = true`
 * (verified live, see docs/TECHNICAL_RESEARCH.md R-30), so the registry is
 * compiled with plain solc to EVM bytecode — no resolc/PolkaVM toolchain.
 *
 * solc is intentionally NOT a repo dependency (it is ~10 MB and only needed
 * to regenerate the committed artifact). To rebuild:
 *
 *   npm i --no-save solc@0.8.28
 *   node contracts/compile-registry.mjs
 *
 * Writes:
 *   contracts/KaizenRunRegistry.artifact.json           (abi + bytecode)
 *   packages/engine/src/v3/anchor/registry-artifact.ts  (same, as TS const)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const PINNED = '0.8.28';
let solc;
try {
  solc = (await import('solc')).default;
} catch {
  console.error(`solc not installed. Run: npm i --no-save solc@${PINNED}`);
  process.exit(1);
}
if (!solc.version().startsWith(PINNED)) {
  console.error(`expected solc ${PINNED}, got ${solc.version()}`);
  process.exit(1);
}
const source = fs.readFileSync(path.join(here, 'KaizenRunRegistry.sol'), 'utf8');
const settings = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: 'paris',
  outputSelection: {
    '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.methodIdentifiers'] },
  },
};
const out = JSON.parse(
  solc.compile(JSON.stringify({ language: 'Solidity', sources: { 'KaizenRunRegistry.sol': { content: source } }, settings })),
);
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join('\n'));
  process.exit(1);
}
const c = out.contracts['KaizenRunRegistry.sol'].KaizenRunRegistry;
const artifact = {
  contractName: 'KaizenRunRegistry',
  compiler: `solc ${solc.version()}`,
  evmVersion: settings.evmVersion,
  optimizer: settings.optimizer,
  abi: c.abi,
  methodIdentifiers: c.evm.methodIdentifiers,
  bytecode: `0x${c.evm.bytecode.object}`,
  deployedBytecode: `0x${c.evm.deployedBytecode.object}`,
};
fs.writeFileSync(path.join(here, 'KaizenRunRegistry.artifact.json'), `${JSON.stringify(artifact, null, 2)}\n`);
const ts = `/**
 * GENERATED by contracts/compile-registry.mjs — do not edit by hand.
 * Source: contracts/KaizenRunRegistry.sol (${artifact.compiler}, evm ${artifact.evmVersion}, optimizer runs ${settings.optimizer.runs}).
 */

export const KAIZEN_RUN_REGISTRY_ARTIFACT = ${JSON.stringify(artifact, null, 2)} as const;
`;
fs.writeFileSync(path.join(here, '..', 'packages', 'engine', 'src', 'v3', 'anchor', 'registry-artifact.ts'), ts);
console.log(`compiled with ${artifact.compiler}: init ${c.evm.bytecode.object.length / 2} bytes, runtime ${c.evm.deployedBytecode.object.length / 2} bytes`);
