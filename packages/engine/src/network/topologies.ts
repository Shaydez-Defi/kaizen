/**
 * Network topologies — presets as data + custom topology validation (T-2.1).
 *
 * Resolution is a pure function that runs BEFORE any process, directory, or
 * port is created. It rejects duplicate identities, duplicate well-known
 * keys, role/key mismatches, and configurations that could never function
 * (no validator, too many validators).
 *
 * Genesis authority facts (verified against the real binary 2026-10-10, see
 * docs/TECHNICAL_RESEARCH.md R-05):
 *  - The embedded Local Testnet spec seeds exactly TWO genesis authorities —
 *    Alice (5GrwvaEF…) and Bob (5FHneW46x…) — with staking.validatorCount=2.
 *    Four running processes do NOT make four authorities: any network whose
 *    validator keys exceed {alice, bob} REQUIRES a patched chain spec
 *    (session.keys + staking.stakers + staking.invulnerables +
 *    staking.validatorCount) generated by the ChainSpecService.
 *  - Session key derivation: babe/imOnline/authorityDiscovery keys equal
 *    sr25519(//X) (the dev account itself); the grandpa key is
 *    ed25519(//X) — verified by matching the genesis entries of alice/bob
 *    against `key inspect` output.
 *  - Genesis balances already fund alice…eve (5 UNITS each), so patched-in
 *    validators need no balance surgery.
 *  - All four authorities were observed authoring blocks (BABE rotation) and
 *    GRANDPA finality advanced on a patched 4-authority network; a full node
 *    synced to head with 0 blocks authored. Evidence: docs/PROGRESS.md.
 */

import { KaizenError } from '../errors';
import type {
  CustomTopologyInput,
  CustomTopologyNodeInput,
  NetworkPreset,
  NodeRole,
  WellKnownKey,
} from '../types';

/** Node name pattern (also used for network names). */
export const NAME_PATTERN = /^[a-z0-9][a-z0-9_-]{0,31}$/;

/** Well-known keys that can act as genesis authorities (verified derivations). */
export const AUTHORITY_KEYS: readonly WellKnownKey[] = ['alice', 'bob', 'charlie', 'dave', 'eve', 'ferdie'];

/** The two accounts that are genesis authorities on the unmodified Local Testnet. */
export const GENESIS_AUTHORITIES: readonly WellKnownKey[] = ['alice', 'bob'];

export const NETWORK_PRESETS: readonly NetworkPreset[] = [
  'single-node',
  'two-node',
  'four-validator',
  'validator-fullnode',
  'custom',
];

/** Hard cap on custom networks (operational sanity, not a protocol limit). */
export const MAX_CUSTOM_NODES = 8;
/** Hard cap on validators per network (one per well-known authority key). */
export const MAX_VALIDATORS = AUTHORITY_KEYS.length;

export interface TopologyNodeTemplate {
  /** Stable id suffix: 'a', 'b', 'c', … (also fixes start/stop ordering). */
  suffix: string;
  /** Node display name suffix. */
  nameSuffix: string;
  role: NodeRole;
  wellKnownKey?: WellKnownKey;
}

export interface TopologyPlan {
  /** 'dev' → `--dev` chain; 'local-spec' → generated Local Testnet spec. */
  chain: 'dev' | 'local-spec';
  /** Validator keys that must be present in the genesis authority set. */
  authorityKeys: WellKnownKey[];
  /** Ordered node templates; index 0 is the bootnode seed. */
  nodes: TopologyNodeTemplate[];
}

/** True when the Local Testnet spec must be patched to carry these authorities. */
export function needsAuthorityPatch(plan: TopologyPlan): boolean {
  if (plan.chain !== 'local-spec') return false;
  return plan.authorityKeys.some((k) => !GENESIS_AUTHORITIES.includes(k));
}

const SUFFIXES = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h'] as const;

/**
 * Resolve a topology plan for a preset (optionally with custom nodes) or throw
 * INVALID_INPUT with per-problem details. Pure: touches no filesystem, no
 * processes, no ports.
 */
export function resolveTopology(
  preset: NetworkPreset,
  custom?: CustomTopologyInput,
): TopologyPlan {
  switch (preset) {
    case 'single-node':
      return {
        chain: 'dev',
        authorityKeys: ['alice'],
        nodes: [validator('a', 'alice')],
      };
    case 'two-node':
      return {
        chain: 'local-spec',
        authorityKeys: ['alice', 'bob'],
        nodes: [validator('a', 'alice'), validator('b', 'bob')],
      };
    case 'four-validator':
      return {
        chain: 'local-spec',
        authorityKeys: ['alice', 'bob', 'charlie', 'dave'],
        nodes: [
          validator('a', 'alice'),
          validator('b', 'bob'),
          validator('c', 'charlie'),
          validator('d', 'dave'),
        ],
      };
    case 'validator-fullnode':
      return {
        chain: 'local-spec',
        authorityKeys: ['alice', 'bob', 'charlie'],
        nodes: [
          validator('a', 'alice'),
          validator('b', 'bob'),
          validator('c', 'charlie'),
          { suffix: 'd', nameSuffix: 'full', role: 'full' },
        ],
      };
    case 'custom':
      return resolveCustom(custom);
    default: {
      const bad: never = preset;
      throw new KaizenError(
        'INVALID_INPUT',
        `Unknown preset "${String(bad)}" — supported: ${NETWORK_PRESETS.join(', ')}`,
        { preset: String(bad) },
      );
    }
  }
}

function validator(suffix: string, key: WellKnownKey): TopologyNodeTemplate {
  return { suffix, nameSuffix: key, role: 'validator', wellKnownKey: key };
}

function resolveCustom(custom?: CustomTopologyInput): TopologyPlan {
  const issues: string[] = [];
  const nodes = custom?.nodes;

  if (!Array.isArray(nodes) || nodes.length === 0) {
    throw new KaizenError(
      'INVALID_INPUT',
      'Custom topology requires a non-empty "nodes" array',
      { problems: ['custom.nodes must be a non-empty array'] },
    );
  }
  if (nodes.length > MAX_CUSTOM_NODES) {
    issues.push(`custom topology supports at most ${MAX_CUSTOM_NODES} nodes (got ${nodes.length})`);
  }

  const seenNames = new Set<string>();
  const seenKeys = new Set<string>();
  const templates: TopologyNodeTemplate[] = [];
  let validatorCount = 0;

  nodes.forEach((node: CustomTopologyNodeInput, i: number) => {
    const label = `nodes[${i}]`;
    if (!NAME_PATTERN.test(node?.name ?? '')) {
      issues.push(`${label}: invalid name "${node?.name}" — must match ${NAME_PATTERN}`);
      return;
    }
    if (seenNames.has(node.name)) {
      issues.push(`${label}: duplicate node name "${node.name}"`);
    }
    seenNames.add(node.name);

    if (node.role !== 'validator' && node.role !== 'full') {
      issues.push(`${label}: invalid role "${String(node.role)}" — must be "validator" or "full"`);
      return;
    }

    if (node.role === 'validator') {
      validatorCount++;
      if (!node.wellKnownKey) {
        issues.push(
          `${label}: validator "${node.name}" requires a wellKnownKey (${AUTHORITY_KEYS.join(', ')}) — ` +
            'validators must be genesis authorities, keys are not generated ad hoc',
        );
      } else if (!AUTHORITY_KEYS.includes(node.wellKnownKey as WellKnownKey)) {
        issues.push(
          `${label}: unknown validator wellKnownKey "${node.wellKnownKey}" — supported: ${AUTHORITY_KEYS.join(', ')}`,
        );
      } else if (seenKeys.has(node.wellKnownKey)) {
        issues.push(`${label}: duplicate wellKnownKey "${node.wellKnownKey}"`);
      } else {
        seenKeys.add(node.wellKnownKey);
      }
    } else if (node.wellKnownKey) {
      issues.push(
        `${label}: full node "${node.name}" must not set wellKnownKey (keys are validator identity)`,
      );
    }

    if (templates.length < MAX_CUSTOM_NODES) {
      templates.push({
        suffix: SUFFIXES[templates.length] ?? String(templates.length),
        nameSuffix: node.name,
        role: node.role,
        wellKnownKey: (node.wellKnownKey as WellKnownKey | undefined) ?? undefined,
      });
    }
  });

  if (issues.length === 0 && validatorCount === 0) {
    issues.push('custom topology needs at least one validator node');
  }

  if (issues.length > 0) {
    throw new KaizenError(
      'INVALID_INPUT',
      `Invalid custom topology: ${issues.join('; ')}`,
      { problems: issues },
    );
  }

  return {
    chain: 'local-spec',
    authorityKeys: templates
      .filter((t) => t.role === 'validator')
      .map((t) => t.wellKnownKey as WellKnownKey),
    nodes: templates,
  };
}
